    private static Dictionary<string, string>? _reverse;

    /// <summary>查英文翻譯；未收錄回 null（呼叫方回退繁中原文）。</summary>
    public static string? Lookup(string zh) => Map.TryGetValue(zh, out var en) ? en : null;

    /// <summary>
    /// 反查：英文字串 → 對應的繁中原文鍵；查不到回 null。
    /// 用途：語言模式的「原文保存」正規化——英語模式下寫進控制項的英文字串
    /// （程式碼 T() 的產物）會被 FromOriginal 當成「原文」存走，之後切簡體就永遠卡英文。
    /// 存槽前先 Reverse 回繁中鍵，三方往返才能可逆。
    /// </summary>
    public static string? Reverse(string en)
    {
        if (_reverse is null)
        {
            var d = new Dictionary<string, string>();
            foreach (var (k, v) in Map)
                if (!d.ContainsKey(v)) d[v] = k;   // 多鍵同譯取先出現者
            _reverse = d;
        }
        return _reverse.TryGetValue(en, out var zh) ? zh : null;
    }

