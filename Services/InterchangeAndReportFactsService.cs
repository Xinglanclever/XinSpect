    public static string BuildOfflineManualHtml(string title = "曦覽 XinSpect 離線手冊", DateTimeOffset? generatedAtUtc = null)
    {
        string safeTitle = HtmlReportService.Escape(title);
        var sb = new StringBuilder();
        sb.Append("<!DOCTYPE html>\n<html lang=\"zh-Hant\">\n<head>\n<meta charset=\"utf-8\">\n");
        sb.Append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n");
        sb.Append("<title>").Append(safeTitle).Append("</title>\n");
        sb.Append("""
            <style>
            body{font-family:"Microsoft JhengHei",sans-serif;margin:28px;max-width:980px;color:#111;background:#fff}
            h1{font-size:24px;border-bottom:2px solid #333;padding-bottom:8px}
            h2{font-size:18px;margin-top:30px;color:#238636}
            h3{font-size:15px;margin-bottom:6px}
            article{margin:18px 0;padding-bottom:10px;border-bottom:1px solid #eee}
            p{margin:6px 0;line-height:1.55}
            .meta{color:#555;font-size:12px}
            .risk{color:#7a5700;font-size:13px}
            @media print{body{margin:10px}h2{page-break-after:avoid}article{page-break-inside:avoid}}
            </style>
            """);
        sb.Append("</head>\n<body>\n");
        sb.Append("<h1>").Append(safeTitle).Append("</h1>\n");
        sb.Append("<p class=\"meta\">產生時間（UTC）：")
          .Append(HtmlReportService.Escape((generatedAtUtc ?? DateTimeOffset.UtcNow).ToString("yyyy-MM-dd HH:mm:ss'Z'")))
          .Append(" ・ 本檔自足，無 CDN、無字型、無指令碼；可離線開啟與列印。說明條目 ")
          .Append(HelpCatalog.All.Count.ToString(CultureInfo.InvariantCulture)).AppendLine(" 條。</p>");
        foreach (var group in HelpCatalog.All.OrderBy(x => PageOf(x.Key), StringComparer.Ordinal)
                                            .ThenBy(x => x.Key, StringComparer.Ordinal)
                                            .GroupBy(x => PageOf(x.Key), StringComparer.Ordinal))
        {
            sb.Append("<h2>").Append(HtmlReportService.Escape(group.Key)).Append("</h2>\n");
            foreach (var entry in group)
            {
                sb.Append("<article><h3>").Append(HtmlReportService.Escape(entry.Value.Title)).Append("</h3>");
                sb.Append("<p>").Append(HtmlReportService.Escape(entry.Value.What)).Append("</p>");
                sb.Append("<p>").Append(HtmlReportService.Escape(entry.Value.Does)).Append("</p>");
                sb.Append("<p class=\"risk\">").Append(HtmlReportService.Escape(entry.Value.RiskLine)).Append("</p>");
                sb.Append("</article>\n");
            }
        }
        sb.Append("<p class=\"meta\">界線：手冊是 HelpCatalog 的離線再呈現；內容正確性仍由維護者與實際程式碼對照，不等同外部規格背書。</p>\n");
        sb.Append("</body>\n</html>\n");
        return sb.ToString();
    }

    private static string PageOf(string key)
    {
        int slash = key.IndexOf('/', StringComparison.Ordinal);
        return slash < 0 ? "全站" : key[..slash];
    }

