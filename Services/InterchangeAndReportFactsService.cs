        catch (Exception)
        {
            return Unavailable(at, SnapshotKey, CatXt, "時間膠囊檔案整合", "快照無法載入或完整性不符——不猜內容",
                FactAvailability.ReadError, "檔案格式或完整性不符；或存取條件不滿足");
        }
    }

