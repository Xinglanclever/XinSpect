    public static HardwareFact SnapshotFact(DateTimeOffset at, string? path = null, Func<string, string>? loader = null)
    {
        if (path is null) return Collect(at).Single(f => f.Key == SnapshotKey);
        try
        {
            string summary = loader is null ? ReadSnapshotSummary(path) : loader(path);
            return new HardwareFact(SnapshotKey, CatXt, "時間膠囊檔案整合",
                summary + "。界線：摘要只含版本與筆數，不含原始敏感值。",
                "摘要", "HardwareSnapshotService.Load", FactTrustLevel.Derived, false, at);
