        var snapshot = HardwareSnapshotService.Load(path);
        string redacted = snapshot.SensitiveValuesPreserved ? "false" : "true";
        return $"schemaVersion={snapshot.SchemaVersion.ToString(CultureInfo.InvariantCulture)}"
