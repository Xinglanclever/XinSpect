    [SpecRef("本專案的鍵匯出約定（非外部規格）：公開鍵轉 PascalCase 常數；重複鍵以數字後綴避免同名的 C# 宣告。")]
    public static string GenerateCSharpConstants(IEnumerable<string> keys)
    {
        var seen = new HashSet<string>(StringComparer.Ordinal);
        var sb = new StringBuilder();
        sb.AppendLine("// Generated by XinSpect XT-001. 這是鍵名常數，不是硬體值。");
        sb.AppendLine("namespace XinSpect;");
        sb.AppendLine();
        sb.AppendLine("public static class XinSpectFactKeys");
        sb.AppendLine("{");
        foreach (string raw in keys ?? [])
        {
            if (string.IsNullOrWhiteSpace(raw)) continue;
            string id = CSharpIdentifier(raw);
            if (!seen.Add(id))
            {
                int n = 2;
                while (!seen.Add(id + n.ToString(CultureInfo.InvariantCulture))) n++;
                id += n.ToString(CultureInfo.InvariantCulture);
            }
            sb.Append("    public const string ").Append(id)
              .Append(" = \"").Append(EscapeCSharp(raw)).AppendLine("\";");
        }
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string CSharpIdentifier(string key)
    {
        var sb = new StringBuilder("Key");
        bool upper = true;
        foreach (char c in key)
        {
            if (char.IsAsciiLetterOrDigit(c))
            {
                sb.Append(upper ? char.ToUpperInvariant(c) : char.ToLowerInvariant(c));
                upper = false;
            }
            else upper = true;
        }
        return sb.Length == 1 ? "KeyX" : sb.ToString();
    }

    private static string EscapeCSharp(string value)
        => value.Replace("\\", "\\\\", StringComparison.Ordinal)
                .Replace("\"", "\\\"", StringComparison.Ordinal);

