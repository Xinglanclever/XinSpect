    // ── RS-001 匿名求助範本 ────────────────────────────────────────────────

    public static string BuildAnonymousHelpTemplate(IEnumerable<HardwareFact> facts, string? machineLabel = null)
    {
        var sb = new StringBuilder();
        sb.AppendLine("## 曦覽 XinSpect 匿名求助範本");
        sb.AppendLine();
        sb.AppendLine("> 此範本刻意不含本機路徑、序號、主機名稱、MAC、UUID 或可識別資料；敏感欄位一律遮蔽。它不等於已送出任何資訊。");
        if (!string.IsNullOrWhiteSpace(machineLabel))
            sb.Append("- 機器型號（使用者可自願提供）：").Append(OneLine(machineLabel)).AppendLine();
        sb.AppendLine();
        sb.AppendLine("| 鍵 | 項目 | 值 | 狀態 |");
        sb.AppendLine("|---|---|---|---|");
        foreach (var f in (facts ?? []).OrderBy(x => x.Key, StringComparer.Ordinal))
        {
            string value = ShouldRedact(f) ? RedactedValue : OneLine(f.Value);
            if (string.IsNullOrWhiteSpace(value)) value = "（無值）";
            sb.Append("| ").Append(OneLine(f.Key))
              .Append(" | ").Append(OneLine(f.Name))
              .Append(" | ").Append(value)
              .Append(" | ").Append(f.Availability.ToString()).AppendLine();
        }
        return sb.ToString();
    }

    private static bool ShouldRedact(HardwareFact f)
        => f.Sensitive || IsSensitiveKey(f.Key) || ContainsPath(f.Value);

    private static bool IsSensitiveKey(string key)
    {
        string k = key.ToLowerInvariant();
        return k.Contains("serial", StringComparison.Ordinal)
            || k.Contains("host", StringComparison.Ordinal)
            || k.Contains("user", StringComparison.Ordinal)
            || k.Contains("mac", StringComparison.Ordinal)
            || k.Contains("uuid", StringComparison.Ordinal)
            || k.Contains("license", StringComparison.Ordinal)
            || k.Contains("product", StringComparison.Ordinal)
            || k.Contains("token", StringComparison.Ordinal)
            || k.Contains("secret", StringComparison.Ordinal)
            || k.Contains("password", StringComparison.Ordinal);
    }

    private static bool ContainsPath(string value)
        => value.Contains(":\\", StringComparison.Ordinal)
         || value.Contains("\\\\", StringComparison.Ordinal)
         || value.StartsWith("/", StringComparison.Ordinal);

    private static string OneLine(string value)
        => Regex.Replace(value.Replace("\r", " ", StringComparison.Ordinal)
            .Replace("\n", " ", StringComparison.Ordinal), @"\s+", " ");

    // ── RS-003 SVG ─────────────────────────────────────────────────────────

    [SpecRef("Scalable Vector Graphics 1.1 基礎形状約定：svg 根元素須有 xmlns；rect/text 的坐標為使用者空間長度。")]
    public static string BuildSvgChart(string title, IEnumerable<(string Label, double Value)> values)
    {
        var rows = (values ?? []).Where(x => double.IsFinite(x.Value) && x.Value >= 0).ToList();
        int width = 480;
        int height = Math.Max(170, 52 + rows.Count * 26);
        double max = rows.Count == 0 ? 0 : rows.Max(x => x.Value);
        string safeTitle = HtmlReportService.Escape(string.IsNullOrWhiteSpace(title) ? "圖表" : title);
        var sb = new StringBuilder();
        sb.Append("<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"").Append(width)
          .Append("\" height=\"").Append(height)
          .Append("\" viewBox=\"0 0 ").Append(width).Append(' ').Append(height)
          .Append("\" role=\"img\" aria-label=\"").Append(safeTitle).Append("\">");
        sb.Append("<rect width=\"100%\" height=\"100%\" fill=\"#ffffff\"/>");
        sb.Append("<text x=\"18\" y=\"26\" font-family=\"Segoe UI,Microsoft JhengHei,sans-serif\" font-size=\"17\" fill=\"#222\">")
          .Append(safeTitle).Append("</text>");
        for (int i = 0; i < rows.Count; i++)
        {
            var row = rows[i];
            int y = 48 + i * 26;
            double ratio = max <= 0 ? 0 : row.Value / max;
            int bar = (int)Math.Round(ratio * 270, MidpointRounding.AwayFromZero);
            string label = HtmlReportService.Escape(row.Label);
            string num = row.Value.ToString("0.###", CultureInfo.InvariantCulture);
            sb.Append("<text x=\"18\" y=\"").Append(y + 13).Append("\" font-size=\"12\" fill=\"#333\">").Append(label).Append("</text>");
            sb.Append("<rect x=\"160\" y=\"").Append(y).Append("\" width=\"").Append(bar)
              .Append("\" height=\"18\" fill=\"#3FB950\" aria-label=\"").Append(label).Append(' ').Append(num).Append("\"/>");
            sb.Append("<text x=\"").Append(Math.Max(160, 438)).Append("\" y=\"").Append(y + 13)
              .Append("\" font-size=\"12\" fill=\"#555\">").Append(num).Append("</text>");
        }
        sb.Append("</svg>");
        return sb.ToString();
    }

    // ── RS-004 xlsx ────────────────────────────────────────────────────────

    public static void WriteXlsx(string path, IReadOnlyList<HardwareFact> facts,
        SensitiveValuePolicy policy = SensitiveValuePolicy.Redact)
    {
        if (string.IsNullOrWhiteSpace(path)) throw new ArgumentException("匯出路徑不可空白。", nameof(path));
        string full = Path.GetFullPath(path);
        string? parent = Path.GetDirectoryName(full);
        if (parent is null || !Directory.Exists(parent))
            throw new DirectoryNotFoundException("目標資料夾不存在；匯入服務不隱式建立路徑。");

        using var fs = new FileStream(full, FileMode.Create, FileAccess.Write);
        using var zip = new ZipArchive(fs, ZipArchiveMode.Create);
        AddEntry(zip, "[Content_Types].xml", XlsxContentTypes);
        AddEntry(zip, "_rels/.rels", XlsxPackageRels);
        AddEntry(zip, "xl/workbook.xml", XlsxWorkbook);
        AddEntry(zip, "xl/_rels/workbook.xml.rels", XlsxWorkbookRels);
        AddEntry(zip, "xl/styles.xml", XlsxStyles);
        AddEntry(zip, "xl/worksheets/sheet1.xml", BuildSheetXml(facts ?? [], policy));
    }

    public static Task WriteXlsxAsync(string path, IReadOnlyList<HardwareFact> facts,
        SensitiveValuePolicy policy = SensitiveValuePolicy.Redact, CancellationToken cancellationToken = default)
        => Task.Run(() => WriteXlsx(path, facts, policy), cancellationToken);

    private static void AddEntry(ZipArchive zip, string name, string text)
    {
        var entry = zip.CreateEntry(name, CompressionLevel.Optimal);
        using var stream = entry.Open();
        using var writer = new StreamWriter(stream, new UTF8Encoding(false));
        writer.Write(text);
    }

    private static string BuildSheetXml(IReadOnlyList<HardwareFact> facts, SensitiveValuePolicy policy)
    {
        string[] headers = ["key", "category", "name", "value", "unit", "trust", "availability", "measured_at_utc", "numeric_value", "sensitive"];
        var sb = new StringBuilder();
        sb.Append("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>");
        sb.Append("<worksheet xmlns=\"http://schemas.openxmlformats.org/spreadsheetml/2006/main\">");
        sb.Append("<sheetData>");
        sb.Append("<row r=\"1\">");
        for (int c = 0; c < headers.Length; c++)
            AppendText(sb, CellAddress(1, c), headers[c]);
        sb.Append("</row>");
        int row = 2;
        foreach (var f in facts)
        {
            bool redact = policy == SensitiveValuePolicy.Redact && f.Sensitive && !string.IsNullOrEmpty(f.Value);
            string value = redact ? "（敏感值已遮蔽）" : f.Value;
            sb.Append("<row r=\"").Append(row).Append("\">");
            AppendText(sb, CellAddress(row, 0), f.Key);
            AppendText(sb, CellAddress(row, 1), f.Category);
            AppendText(sb, CellAddress(row, 2), f.Name);
            AppendText(sb, CellAddress(row, 3), value);
            AppendText(sb, CellAddress(row, 4), f.Unit);
            AppendText(sb, CellAddress(row, 5), f.Trust.ToString());
            AppendText(sb, CellAddress(row, 6), f.Availability.ToString());
            AppendText(sb, CellAddress(row, 7), f.MeasuredAtUtc.ToString("O", CultureInfo.InvariantCulture));
            if (f.NumericValue is { } n && double.IsFinite(n))
            {
                sb.Append("<c r=\"").Append(CellAddress(row, 8)).Append("\"><v>")
                  .Append(n.ToString("0.################", CultureInfo.InvariantCulture)).Append("</v></c>");
            }
            else AppendText(sb, CellAddress(row, 8), "");
            AppendText(sb, CellAddress(row, 9), f.Sensitive ? "TRUE" : "FALSE");
            sb.Append("</row>");
            row++;
        }
        sb.Append("</sheetData></worksheet>");
        return sb.ToString();
    }

    private static void AppendText(StringBuilder sb, string cell, string value)
        => sb.Append("<c r=\"").Append(cell).Append("\" t=\"inlineStr\"><is><t xml:space=\"preserve\">")
             .Append(XmlEscape(value ?? "")).Append("</t></is></c>");

    private static string CellAddress(int row, int col) => ColumnName(col) + row.ToString(CultureInfo.InvariantCulture);

    private static string ColumnName(int index)
    {
        int n = index + 1;
        var chars = new List<char>();
        while (n > 0)
        {
            int rem = (n - 1) % 26;
            chars.Insert(0, (char)('A' + rem));
            n = (n - 1) / 26;
        }
        return new string(chars.ToArray());
    }

    private static string XmlEscape(string value)
        => value.Replace("&", "&amp;", StringComparison.Ordinal)
                .Replace("<", "&lt;", StringComparison.Ordinal)
                .Replace(">", "&gt;", StringComparison.Ordinal)
                .Replace("\"", "&quot;", StringComparison.Ordinal)
                .Replace("'", "&apos;", StringComparison.Ordinal);

