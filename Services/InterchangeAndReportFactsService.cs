    // ── XT-004 本機檔案觸發 ────────────────────────────────────────────────

    public static string? ReadTriggerToken(string directory, string fileName = ".xinspect-trigger")
    {
        if (!Directory.Exists(directory))
            throw new DirectoryNotFoundException("觸發目錄不存在——讀不到就是不猜");
        string path = Path.Combine(directory, fileName);
        return File.Exists(path) ? File.ReadAllText(path).Trim() : null;
    }

    public sealed class LocalFileTriggerWatcher : IDisposable
    {
        private readonly FileSystemWatcher _watcher;

        public LocalFileTriggerWatcher(string directory, string fileName = ".xinspect-trigger")
        {
            if (!Directory.Exists(directory))
                throw new DirectoryNotFoundException("觸發目錄不存在——不自動建立目錄，避免把副作用藏進讀取路徑");
            _watcher = new FileSystemWatcher(directory, fileName)
            {
                NotifyFilter = NotifyFilters.FileName | NotifyFilters.LastWrite,
                EnableRaisingEvents = false,
            };
            _watcher.Created += (_, e) => _triggered?.Invoke(e.Name ?? "");
            _watcher.Changed += (_, e) => _triggered?.Invoke(e.Name ?? "");
            _watcher.Renamed += (_, e) => _triggered?.Invoke(e.Name ?? "");
        }

        private Action<string>? _triggered;
        public event Action<string> Triggered { add => _triggered += value; remove => _triggered -= value; }

        public bool CurrentTriggerPresent => File.Exists(Path.Combine(_watcher.Path, _watcher.Filter));

        public void TestFire(string name) => _triggered?.Invoke(name);

        public void Start() => _watcher.EnableRaisingEvents = true;
        public void Stop() => _watcher.EnableRaisingEvents = false;

        public void Dispose()
        {
            _watcher.EnableRaisingEvents = false;
            _watcher.Dispose();
        }
    }

