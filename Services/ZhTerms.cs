    /// <summary>簡體→繁體的反向表（程式啟動時由正向表建出）。</summary>
    public static readonly (string Simp, string Trad)[] ToTrad =
        ToSimp.Select(p => (p.Simp, p.Trad)).ToArray();

    /// <summary>套用詞組替換。</summary>
    public static string ApplyToSimp(string text)
    {
        foreach (var (trad, simp) in ToSimp)
            text = text.Replace(trad, simp);
        return text;
    }

    /// <summary>套用反向替換。</summary>
    public static string ApplyToTrad(string text)
    {
        foreach (var (simp, trad) in ToTrad)
            text = text.Replace(simp, trad);
        return text;
    }
