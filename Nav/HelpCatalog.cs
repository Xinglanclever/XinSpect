namespace XinSpect;

/// <summary>說明條目的風險等級；決定圓圈問號的顏色與提示末段那句話的口吻。</summary>
public enum HelpRisk
{
    /// <summary>只讀數字、不動任何東西。</summary>
    ReadOnly,
    /// <summary>會改動系統設定或造成可感知的副作用，但可還原。</summary>
    Caution,
    /// <summary>會寫入硬體、可能當機／掉資料／需要重開機才救得回來。</summary>
    Danger,
}

/// <summary>一條說明：這是什麼、能做什麼、動它安不安全。</summary>
public sealed class HelpEntry
{
    /// <summary>提示第一行的粗體標題，通常等於版面上的名稱。</summary>
    public string Title { get; init; } = "";
    /// <summary>這是什麼（涵義與介紹）。</summary>
    public string What { get; init; } = "";
    /// <summary>它的功能：怎麼讀這些數字，或按下去會發生什麼。</summary>
    public string Does { get; init; } = "";
    /// <summary>風險等級。</summary>
    public HelpRisk Risk { get; init; } = HelpRisk.ReadOnly;
    /// <summary>危險性／安全性補述；留空則使用該等級的預設說法。</summary>
    public string? Safety { get; init; }

    /// <summary>提示最後一行（灰底那格）的完整句子。</summary>
    public string RiskLine => Risk switch
    {
        HelpRisk.Danger => "危險：" + (Safety ?? "這裡會直接寫入硬體，設錯可能當機或需要清除 CMOS 才回得來。"),
        HelpRisk.Caution => "注意：" + (Safety ?? "這裡會改動系統設定，雖然可以還原，但請先看懂再動。"),
        _ => "安全：" + (Safety ?? "純唯讀。只是把硬體與作業系統回報的數字讀出來顯示，不寫入任何設定，也不影響穩定性。"),
    };
}

