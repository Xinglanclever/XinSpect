namespace XinSpect;

/// <summary>一個版本的更新紀錄：版號、日期、一句話總結，以及逐項改動。</summary>
public sealed class ChangeEntry
{
    /// <summary>版本字串（例如 <c>1.7.4</c>）；還沒有版本編號的階段就直接寫階段名。</summary>
    public string Version { get; init; } = "";

    /// <summary>發佈日期 <c>yyyy-MM-dd</c>。倉庫建立前的版本沒有可靠日期，留空。</summary>
    public string Date { get; init; } = "";

    /// <summary>一句話總結這一版做了什麼。</summary>
    public string Title { get; init; } = "";

    /// <summary>逐項改動；每一項都要對得上真的做過的事。</summary>
    public IReadOnlyList<string> Items { get; init; } = [];

    /// <summary>true＝進入版本控制之前的版本，只有階段層級的描述。</summary>
    public bool BeforeRepo { get; init; }

    /// <summary>版面上顯示的日期。沒有紀錄就如實說沒有，不留白也不編一個出來。</summary>
    public string DateText => Date.Length > 0 ? Date : "日期未留下紀錄";

    /// <summary>版面上的逐項改動：一個 TextBlock 一段，每行一個項目符號。</summary>
    public string ItemsText => string.Join("\n", Items.Select(i => "・" + i));
}

