# -*- coding: utf-8 -*-
"""補上 README §三 缺的那一段：★ 錨記會被樸素解析漏掉。

README:98 描述了失效模式（「認不出來，宣告變成 95 而非 105，而矩陣列數一直數對。
工具壞掉被讀成文件壞掉。」），但沒有寫出**是哪一種格式變化**造成認不出來。
於是同一個坑被踩了三次（先前的稽核報告、我自己兩次）。

補上具體的辨識規則——不寫的話，第四個人還會踩。
"""
import io
import sys

sys.stdout.reconfigure(encoding='utf-8')
p = 'docs/ULTIMATE-1000/README.md'
t = io.open(p, encoding='utf-8').read()

anchor = '認不出來（宣告變成 95 而非 105），而矩陣列數一直數對。工具壞掉被讀成文件壞掉。'

addition = '''認不出來（宣告變成 95 而非 105），而矩陣列數一直數對。工具壞掉被讀成文件壞掉。

### 附：矩陣列的辨識規則（2026-10-16 補）

上面那句「認不出來」在階段二具體重演了**三次**（先前的稽核報告一次、實作者兩次），
所以把造成認不出來的格式細節寫在這裡——**這一段的存在，是為了讓第四個人不必再踩一次**：

1. **`★` 錨記夾在 `|` 與 `ID` 之間**。階段二有三列寫成 `| ★P2-034 | …`（P2-034／P2-036／P2-064）。
   用 `StartsWith("| P2-")` 比對會**安靜地漏掉這三列**，數出 102 而非 105。
2. **資料列與表頭的欄位數不同**。表頭與分隔列有尾端 `|`，
   所以 `Split('|')` 得到 10 段；**資料列沒有尾端 `|`，得到 9 段**。
   把門檻寫成 `< 10` 會濾掉**全部**資料列，數出 0。
3. **正確的辨識式**：`^\\|\\s*★?\\s*(P\\d+-\\d{3})\\s*\\|`——允許 `★` 與空白。

**因此「數出來的列數」不是可信的證據，除非同時說出用了什麼辨識式。**
兩次獨立的錯誤可以得出同一個數字（102），而那個數字仍然是錯的——
那不代表兩個工具都對，只代表**兩個工具壞在同一個地方**。
'''

if anchor in t:
    t = t.replace(anchor, addition, 1)
    io.open(p, 'w', encoding='utf-8', newline='').write(t)
    print('已補上 README §三 的矩陣列辨識規則')
else:
    print('!! 找不到錨點')
    i = t.find('認不出來')
    print(repr(t[i - 100:i + 200]) if i >= 0 else '（完全找不到）')
