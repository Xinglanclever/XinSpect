# -*- coding: utf-8 -*-
"""Assemble the English edition of the whitepaper.

The generated appendix tables are language-neutral (they list identifiers), but their intro
paragraphs and column headers are authored in Chinese. This script translates those few
strings so the English edition reads consistently, and uses the authored English Appendices
B and D. The complete Chinese rationale text for those two appendices is reproduced in the
Chinese editions.
"""
import io, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WP = os.path.join(ROOT, 'work', 'wp')
EN = os.path.join(WP, 'en')

BODY = ['00_front.md', '10.md', '20.md', '30.md', '40.md', '50.md', '60_gov.md', '90_intro.md']

# Appendix order: heading, and either a generated fragment under work/wp/ or an authored
# English fragment under work/wp/en/.
SECTIONS = [
    ('# Appendix A — Full fact-key catalogue', 'generated', 'a_keys.md'),
    ('# Appendix B — Dynamic key families', 'authored', '91_families.md'),
    ('# Appendix C — Reconciliation rule index', 'generated', 'c_rules.md'),
    ('# Appendix D — Explicit exemptions (summary)', 'authored', '92_exempt.md'),
    ('# Appendix E — Service module index', 'generated', 'e_modules.md'),
    ('# Appendix F — Test file index', 'generated', 'f_tests.md'),
    ('# Appendix G — Document index', 'generated', 'g_docs.md'),
    ('# Appendix H — Glossary', 'authored', '95_glossary.md'),
]

TRANSLATIONS = [
    (r'全目錄共 \*\*(\d+)\*\* 個靜態事實鍵，另有 \*\*(\d+)\*\* 個動態鍵家族（見附錄 B）。',
     r'The catalogue holds **\1** static fact keys, plus **\2** dynamic key families (Appendix B).'),
    (r'\| 前綴 \| 鍵數 \| 主要產生模組 \|', '| Prefix | Keys | Primary producing modules |'),
    (r'\| 事實鍵 \| 產生模組 \|', '| Fact key | Producing modules |'),
    (r'對帳規則共 \*\*(\d+)\*\* 條。判定只有三種：相符、矛盾、無法判定；不給分數、不下真偽結論。',
     r'**\1** reconciliation rules. A verdict is one of three — match, conflict or undecidable — with no score and no authenticity claim.'),
    (r'\| 規則 \| 分區 \| 標題 \| 需要的事實 \| 作用域 \|',
     '| Rule | Partition | Title | Required facts | Scope |'),
    (r'\| 逐碟 \|', '| per-disk |'),
    (r'\| 整機 \|', '| machine |'),
    (r'`Services/` 下共 \*\*(\d+)\*\* 個模組。擁有的鍵數為該檔在 `FactKeyCatalog` 中負責產生的事實鍵數量。',
     r'**\1** modules under `Services/`. "Keys owned" is the number of fact keys the file is responsible for producing in `FactKeyCatalog`.'),
    (r'\| 模組 \| 型別 \| 行數 \| 擁有鍵數 \|', '| Module | Type | Lines | Keys owned |'),
    (r'測試檔共 \*\*(\d+)\*\* 個，`\[Fact\]`／`\[Theory\]` 標記合計 \*\*(\d+)\*\* 處。',
     r'**\1** test files, with **\2** `[Fact]`/`[Theory]` markers in total.'),
    (r'\| 測試檔 \| Fact \| Theory \| 行數 \|', '| Test file | Fact | Theory | Lines |'),
    (r'`docs/` 下共 \*\*(\d+)\*\* 份文件。',
     r'**\1** documents under `docs/`. Titles are given as they appear in the repository.'),
    (r'\| 文件 \| 標題 \| 位元組 \|', '| Document | Title | Bytes |'),
]


def read(rel):
    with io.open(os.path.join(ROOT, rel), encoding='utf-8') as f:
        return f.read()


def localise(text):
    for pattern, replacement in TRANSLATIONS:
        text = re.sub(pattern, replacement, text)
    return text


def english(rel):
    path = os.path.join(EN, rel)
    if not os.path.exists(path):
        raise SystemExit('missing English fragment: ' + path)
    return io.open(path, encoding='utf-8').read().strip('\n')


chunks = [english(n) for n in BODY]

for heading, kind, rel in SECTIONS:
    chunks.append(heading)
    if kind == 'generated':
        text = localise(read(os.path.join('work', 'wp', rel).replace(os.sep, '/')))
        # drop the generator's HTML comment marker; it belongs to the build, not the reader
        text = re.sub(r'^<!-- GENERATED by work/wp_gen\.py[^\n]*-->\n+', '', text.strip('\n'))
        chunks.append(text)
    else:
        chunks.append(english(rel))

doc = '\n\n'.join(c.strip('\n') for c in chunks if c and c.strip()) + '\n'
doc = re.sub(r'\n{4,}', '\n\n\n', doc)

with io.open(os.path.join(ROOT, 'WHITEPAPER.en.md'), 'w', encoding='utf-8', newline='\n') as f:
    f.write(doc)

cjk = len(re.findall(r'[\u3400-\u4dbf\u4e00-\u9fff]', doc))
words = len(re.findall(r'[A-Za-z0-9_.\-/]+', doc))
print('WHITEPAPER.en.md', dict(chars=len(doc), words=words, cjk_left=cjk, lines=doc.count('\n') + 1))
