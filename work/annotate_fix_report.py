"""把 FIX-REPORT 裡經複核為誤的三條結論加上更正註記。

不改寫原文（報告是歷史紀錄），只在對應段落後面插入更正框，
讓下一個讀的人不會照著錯的結論去改對的文件。
"""
import io
import sys

sys.stdout.reconfigure(encoding='utf-8')
p = 'docs/FIX-REPORT-2026-10-16.md'
s = io.open(p, encoding='utf-8').read()

NOTE_P0B = """
> **更正（2026-10-16，複核後）**：這一條**不成立**。以 `work/UltimateAudit`（C#，開頭跑自我檢查
> 與環境探針，離開碼 0）重測：**十階段各 105 列，合計 1,050 個互異 ID，編號連續 1..105，
> 跨階段引用全部可解析**。P3-031 與 P3-043 就在矩陣裡（`STAGE-03-SILICON.md` 的
> `| P3-031 |` 與 `| P3-043 |` 兩列），沒有「只存在於錨點區」這回事。
>
> 誤報的來源已查明：稽核腳本用「字元類別 ＋ 量詞」的樣式認域碼（`[A-Z]+\\d?`），
> 而**本機的 Python 3.11.9 與 .NET 10 兩個引擎都對這種樣式給出錯誤答案**
> （`[A-Z]+` 對 `"F10"` 回 false），於是階段一的 F10 一整列認不出來。
> 認 ID 的樣式（`P\\d{1,2}-\\d{3}`）是好的，所以矩陣列數一直數對——**工具壞掉被讀成文件壞掉**。
"""

NOTE_P0A = """
> **更正（2026-10-16，複核後）**：方向對，**但兩個數字都錯**。
> ① 域碼表的 BY 列不是 6 而是 **5**（矩陣裡帶 `bold.` 前綴的只有 P10-101–P10-105；
> P10-100 是「大膽區標記與不計」本身，屬治理域）。
> ② 真正讓合計對不上 105 的是**另一格**：「治理與計數」列寫 12、實際 **13**。
> ③ 因此「不計就得扣掉、總數變 **99**」也是錯的——應為 **104／1,045**。
> 兩格都已改，十階段域碼表合計現在逐階段等於 105。
"""

NOTE_P2U = """
> **更正（2026-10-16，複核後）**：這一條**不成立**。
> 實測每階段 ★ 數為 2/2/3/3/4/2/2/2/2/2 = **24 個**，沒有任何階段是 0；
> 而 `docs/ULTIMATE-1000/README.md` **從來沒有寫過「全庫 20 個 ★ 錨點」**——
> 那句話不在檔案裡。沒有「宣稱與實際不符」這回事。
"""

inserted = 0
# 對準三個段落的小標題
anchors = [
    ('### P0-②　多階段矩陣列數對不上 105', NOTE_P0B),
    ('### P0-①　階段十：大膽區「不計入承諾」卻被算進 105', NOTE_P0A),
    ('| P2-㉔ | `P2-036`', NOTE_P2U),
]

for anchor, note in anchors:
    i = s.find(anchor)
    if i < 0:
        print('找不到錨點：', anchor)
        continue
    # 插在該段落之後：往下找第一個空行分隔的下一段標題或表格結束
    j = s.find('\n\n', i)
    if j < 0:
        print('找不到插入點：', anchor)
        continue
    s = s[:j] + '\n' + note + s[j:]
    inserted += 1

io.open(p, 'w', encoding='utf-8', newline='').write(s)
print(f'插入 {inserted} 條更正註記')
