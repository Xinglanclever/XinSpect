p = 'Services/FactCoverageReport.cs'
text = io.open(p, encoding='utf-8').read()

# 插在最後一條豁免之後（找最後一個 ["..."] = 行）
matches = list(re.finditer(r'^\s*\["[^"]+"\]\s*=', text, re.M))
assert matches, '找不到任何豁免條目'
last = matches[-1]

# 找到該條目的結尾（到下一個 "};\n" 或下一個非續行）
